export const searchCompanies = (query = '') => {
  if (!query || !query.trim()) {
    return COMPANY_DIRECTORY;
  }
  const q = query.toLowerCase().trim();
  return COMPANY_DIRECTORY.filter(
    (c) =>
      c.ticker.toLowerCase().includes(q) ||
      c.name.toLowerCase().includes(q) ||
      c.sector.toLowerCase().includes(q) ||
      c.industry.toLowerCase().includes(q)
  );
};

export const getCompanyByTicker = (ticker = '') => {
  if (!ticker) return null;
  const clean = ticker.toUpperCase().replace('.NS', '').replace('.BO', '').trim();
  return (
    COMPANY_DIRECTORY.find((c) => c.ticker === clean) ||
    COMPANY_DIRECTORY.find((c) => c.ticker.includes(clean)) ||
    null
  );
};

